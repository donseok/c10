const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const base=path.dirname(__dirname),stem=path.join(base,'적정_차선_원자재_폭설계_쉽게이해하기');
const md=fs.readFileSync(stem+'.md','utf8'),html=fs.readFileSync(stem+'.html','utf8');
const refs=[...md.matchAll(/!?\[[^\]]*\]\(([^)]+)\)/g)].map(m=>m[1]);
for(const ref of refs)assert.ok(fs.existsSync(path.resolve(base,decodeURI(ref.split('#')[0]))),'Missing local reference '+ref);
const idList=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]),ids=new Set(idList);
assert.equal(ids.size,idList.length,'Duplicate HTML ids');
for(const m of html.matchAll(/href="#([^"]+)"/g))assert.ok(ids.has(m[1]),'Broken anchor '+m[1]);
assert.equal((html.match(/<figure>/g)||[]).length,14);
assert.equal((html.match(/src="data:image\/svg\+xml/g)||[]).length,14);
assert.equal((html.match(/<script>/g)||[]).length,1);
assert.ok(html.includes('id="width-explorer"'));
assert.ok(!html.includes('id="width-explorer-slot"'));
assert.ok(!/<script[^>]+src=/.test(html));
assert.ok(!/<em>/.test(html),'Unexpected emphasis from unescaped material wildcard');
assert.ok(!/(?:src|href)="https?:\/\//.test(html),'Unexpected network dependency');
assert.ok(!/SIZE_MNFupdate|RMTL_MNFupdate|COL_WTH_SHR_QTY/.test(md),'Incorrect SQL or field name');
const xml=fs.readFileSync(path.resolve(base,'../../src/query/C102100MNF-query.glue_sql'),'utf8');
for(const key of ['C102100MNF.WTHupdate','C102100MNF.WTHupdate1','C102100MNF.PROCupdate','C102100MNF.PROCupdate1'])assert.ok(xml.includes(`id="${key}"`),'Missing SQL key '+key);
const rawXml=fs.readFileSync(path.resolve(base,'../../src/query/C102100RMTL-query.glue_sql'),'utf8');
assert.ok(rawXml.includes('id="C102100RMTL.update"'));
console.log(`PASS: ${refs.length} local references, ${ids.size} unique anchors, 14 embedded SVG figures, standalone HTML, actual SQL keys.`);
